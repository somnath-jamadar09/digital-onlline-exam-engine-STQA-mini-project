'use strict';
// Builds docs/test-case-matrix.md from the ACTUAL result files, so the matrix cannot drift from what ran.
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const rows = [];

// --- API / unit (JUnit from node:test)
const xml = fs.readFileSync(path.join(ROOT, 'results/api-junit.xml'), 'utf8');
const AREA = { TE: 'Timer expiry', ND: 'Network disconnect / retry / resume', CS: 'Concurrent submission', VA: 'Validation & hostile input', RT: 'Real-clock sweeper', GR: 'Grading logic (unit)' };
const LEVEL = { TE: 'API, fake clock', ND: 'API', CS: 'API', VA: 'API', RT: 'API, real clock', GR: 'Unit' };
for (const m of xml.matchAll(/<testcase name="([^"]+)"[^>]*?(\/>|>)/g)) {
  const name = m[1].replace(/&quot;/g, '"').replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&apos;/g, "'");
  const id = name.split(':')[0];
  const pre = id.split('-')[0];
  if (!AREA[pre]) continue;
  rows.push({ id, area: AREA[pre], level: LEVEL[pre], what: name.slice(id.length + 2), pass: m[2] === '/>' });
}

// --- Playwright UI
const ui = JSON.parse(fs.readFileSync(path.join(ROOT, 'results/ui-results.json'), 'utf8'));
const uiArea = (n) => (n <= 9 ? 'UI timer synchronicity' : n <= 13 ? 'UI timer expiry' : 'UI network disconnect');
const walk = (s) => {
  (s.specs || []).forEach((sp) => {
    const m = sp.title.match(/^(UI-(\d+)): (.*)$/);
    if (!m) return;
    const t = sp.tests[0];
    rows.push({ id: m[1], area: uiArea(Number(m[2])), level: 'Playwright / Chromium', what: m[3], pass: t.results[t.results.length - 1].status === 'passed' });
  });
  (s.suites || []).forEach(walk);
};
ui.suites.forEach(walk);

// --- Performance verdicts
const perf = JSON.parse(fs.readFileSync(path.join(ROOT, 'results/perf-results.json'), 'utf8'));
perf.verdicts.forEach((v, i) => rows.push({ id: `PF-${String(i + 1).padStart(2, '0')}`, area: `Performance (${v.scenario})`, level: 'Load test', what: `${v.name}${v.detail ? ' - measured: ' + v.detail : ''}`, pass: v.pass }));

const num = (id) => { const m = id.match(/(\d+)/); return m ? Number(m[1]) : 0; };
const order = ['TE', 'ND', 'CS', 'VA', 'RT', 'GR', 'UI', 'PF'];
rows.sort((a, b) => order.indexOf(a.id.split('-')[0]) - order.indexOf(b.id.split('-')[0]) || num(a.id) - num(b.id));

const total = rows.length, passed = rows.filter((r) => r.pass).length;
const byArea = {};
rows.forEach((r) => { const k = r.area.replace(/\(.*\)/, '').trim(); (byArea[k] = byArea[k] || { n: 0, p: 0 }); byArea[k].n++; byArea[k].p += r.pass ? 1 : 0; });

let md = '# Test case matrix\n\nGenerated by `scripts/gen-matrix.js` from the result files of the last runs (`results/api-junit.xml`, `results/ui-results.json`, `results/perf-results.json`).\n\n';
md += `**${passed} of ${total} executed checks passed.**\n\n| Area | Checks | Passed |\n|---|---:|---:|\n`;
for (const [k, v] of Object.entries(byArea)) md += `| ${k} | ${v.n} | ${v.p} |\n`;
md += '\n| ID | Area | Level | What is verified | Result |\n|---|---|---|---|---|\n';
for (const r of rows) md += `| ${r.id} | ${r.area} | ${r.level} | ${r.what.replace(/\|/g, '/')} | ${r.pass ? 'PASS' : '**FAIL**'} |\n`;
fs.mkdirSync(path.join(ROOT, 'docs'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'docs/test-case-matrix.md'), md);
console.log(`matrix: ${passed}/${total} pass;`, JSON.stringify(byArea));
